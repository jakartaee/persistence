package jakarta.persistence.query;

import jakarta.annotation.Nonnull;
import jakarta.persistence.Statement;
import jakarta.persistence.StatementReference;
import jakarta.persistence.Tuple;

import java.util.*;

import static java.util.Collections.emptyMap;

/**
 * A reference to a statement declared using a {@link JakartaQuery}
 * or {@link NativeQuery} annotation. An instance of this
 * class is usually instantiated by a generated method of the
 * {@linkplain jakarta.persistence.metamodel.StaticMetamodel
 * static metamodel} for the annotated program element.
 *
 * @since 4.0
 */
public class StaticStatementReference
        implements StatementReference {

    @Nonnull private final Class<?> annotatedClass;
    @Nonnull private final String annotatedMemberName;
    @Nonnull private final String name;
    @Nonnull private final Tuple arguments;
    @Nonnull private final Map<String, Object> hints;
    @Nonnull private final Set<Statement.Option> options;

    /**
     * Intended for use in code generated by an annotation processor.
     * This constructor overload is adapted to the case where the
     * program element is annotated with {@link QueryOptions}.
     *
     * @param queryName The name of the query, the concatenation of
     *                  the unqualified name of the annotated type,
     *                  with the string {@code "."}, and the name of
     *                  the annotated member
     * @param annotatedClass The annotated class
     * @param annotatedMemberName The name of the annotated member
     * @param arguments The arguments supplied to the parameters
     *                  at runtime
     * @param hints See {@link QueryOptions#hints}
     * @param options All specified {@linkplain Statement.Option options}
     */
    public StaticStatementReference(
            @Nonnull String queryName,
            @Nonnull Class<?> annotatedClass,
            @Nonnull String annotatedMemberName,
            @Nonnull Tuple arguments,
            @Nonnull Map<String, Object> hints,
            @Nonnull Statement.Option... options) {
        this.name = queryName;
        this.annotatedClass = annotatedClass;
        this.annotatedMemberName = annotatedMemberName;
        this.arguments = arguments;
        this.hints = hints;
        this.options = Set.of(options);
    }

    /**
     * Intended for use in code generated by an annotation processor.
     * This constructor overload is adapted to the case where the
     * program element is not annotated with {@link QueryOptions}.
     *
     * @param queryName The name of the query, the concatenation of
     *                  the unqualified name of the annotated type,
     *                  with the string {@code "."}, and the name of
     *                  the annotated member
     * @param annotatedClass The annotated class
     * @param annotatedMemberName The name of the annotated member
     * @param arguments The arguments supplied to the parameters
     *                  at runtime
     */
    public StaticStatementReference(
            @Nonnull String queryName,
            @Nonnull Class<?> annotatedClass,
            @Nonnull String annotatedMemberName,
            @Nonnull Tuple arguments) {
        this(queryName, annotatedClass, annotatedMemberName,
                arguments, emptyMap());
    }

    @Override
    @Nonnull
    public String getName() {
        return name;
    }

    @Override
    @Nonnull
    public Map<String, Object> getHints() {
        return hints;
    }

    @Override
    @Nonnull
    public List<Class<?>> getParameterTypes() {
        return arguments.getElementTypes();
    }

    @Override
    @Nonnull
    public List<String> getParameterNames() {
        return arguments.getAliases();
    }

    @Override
    @Nonnull
    public List<Object> getArguments() {
        return arguments.getValues();
    }

    @Nonnull
    public Class<?> getAnnotatedClass() {
        return annotatedClass;
    }

    @Nonnull
    public String getAnnotatedMemberName() {
        return annotatedMemberName;
    }

    @Override
    @Nonnull
    public Set<Statement.Option> getOptions() {
        return new HashSet<>(options);
    }

    @Override
    public boolean equals(Object obj) {
        if (obj == this) {
            return true;
        }
        else if ((!(obj instanceof StaticStatementReference that))) {
            return false;
        }
        else {
            return Objects.equals(this.name, that.name)
                && Objects.equals(this.arguments, that.arguments)
                && Objects.equals(this.options, that.options)
                && Objects.equals(this.hints, that.hints);
        }
    }

    @Override
    public int hashCode() {
        return Objects.hash(name, arguments);
    }

    @Override
    public String toString() {
        return "StaticStatementReference["
                + "name=" + name + ", "
                + "arguments=" + arguments + ", "
                + "options=" + options + ", "
                + "hints=" + hints
                + ']';
    }
}
